-- Retroactively documented 2026-10-09, numbered 000 (before
-- 001_forecast_snapshot.sql) since this table already existed. It was
-- created directly in Supabase, outside this repo, before any schema
-- tracking started - this file exists purely so the schema is recorded
-- somewhere, not because it still needs running. Confirmed against the
-- live database via information_schema, not guessed from database.py's
-- queries - notably `average`/buy*/sell* are SMALLINT (not INTEGER), id is
-- an identity column (not SERIAL, which is the older sugar for the same
-- thing), and notes is capped at 255 chars.
--
-- CREATE TABLE IF NOT EXISTS makes this safe to run again regardless (e.g.
-- standing up a fresh environment) - a no-op against the live database.

CREATE TABLE IF NOT EXISTS price (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    datetime  TIMESTAMPTZ NOT NULL,
    average   SMALLINT NOT NULL,
    buy100m   SMALLINT NOT NULL,
    buy1b     SMALLINT NOT NULL,
    buy10b    SMALLINT NOT NULL,
    sell100m  SMALLINT NOT NULL,
    sell1b    SMALLINT NOT NULL,
    sell10b   SMALLINT NOT NULL,
    notes     VARCHAR(255) NOT NULL
);
